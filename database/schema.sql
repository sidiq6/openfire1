-- OPENFIRE | MySQL 8.0+ | Run once in a newly created UTF8MB4 database.
SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;
CREATE TABLE IF NOT EXISTS supported_languages (
 code VARCHAR(8) PRIMARY KEY, name VARCHAR(80) NOT NULL, is_active TINYINT(1) NOT NULL DEFAULT 0,
 is_default TINYINT(1) NOT NULL DEFAULT 0, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS admins (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS admin_sessions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, admin_id BIGINT UNSIGNED NOT NULL,
 token_hash CHAR(64) NOT NULL UNIQUE, ip_address VARCHAR(45), user_agent VARCHAR(255),
 expires_at DATETIME NOT NULL, last_seen DATETIME NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (admin_id) REFERENCES admins(id) ON DELETE CASCADE, INDEX (admin_id, expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS login_attempts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, fingerprint CHAR(64) NOT NULL,
 attempted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, INDEX (fingerprint, attempted_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS website_settings (
 setting_key VARCHAR(100) PRIMARY KEY, setting_value TEXT NOT NULL, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS media_library (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, file_path VARCHAR(320) NOT NULL UNIQUE,
 thumbnail_path VARCHAR(320), original_filename VARCHAR(255) NOT NULL, mime_type VARCHAR(100) NOT NULL,
 width INT UNSIGNED NOT NULL, height INT UNSIGNED NOT NULL, byte_size INT UNSIGNED NOT NULL,
 alt_id VARCHAR(255) NOT NULL DEFAULT '', alt_en VARCHAR(255) NOT NULL DEFAULT '',
 caption_id VARCHAR(255) NOT NULL DEFAULT '', caption_en VARCHAR(255) NOT NULL DEFAULT '',
 origin ENUM('seed','upload') NOT NULL DEFAULT 'seed', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS media_translations (
 media_id BIGINT UNSIGNED NOT NULL, lang VARCHAR(8) NOT NULL,
 alt_text VARCHAR(255) NOT NULL DEFAULT '', caption VARCHAR(255) NOT NULL DEFAULT '',
 PRIMARY KEY (media_id, lang), FOREIGN KEY(media_id) REFERENCES media_library(id) ON DELETE CASCADE,
 FOREIGN KEY(lang) REFERENCES supported_languages(code) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS page_sections (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, slug VARCHAR(100) UNIQUE NOT NULL, media_id BIGINT UNSIGNED NULL,
 sort_order INT NOT NULL DEFAULT 0, active TINYINT(1) NOT NULL DEFAULT 1,
 FOREIGN KEY (media_id) REFERENCES media_library(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS section_translations (
 section_id INT UNSIGNED NOT NULL, lang VARCHAR(8) NOT NULL,
 eyebrow TEXT NOT NULL, title TEXT NOT NULL, body TEXT NOT NULL,
 button_label VARCHAR(160) NOT NULL DEFAULT '', button_label_secondary VARCHAR(160) NOT NULL DEFAULT '',
 PRIMARY KEY (section_id,lang), FOREIGN KEY (section_id) REFERENCES page_sections(id) ON DELETE CASCADE,
 FOREIGN KEY (lang) REFERENCES supported_languages(code) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS menu_categories (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, slug VARCHAR(120) UNIQUE NOT NULL,
 sort_order INT NOT NULL DEFAULT 0, active TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS menu_category_translations (
 category_id INT UNSIGNED NOT NULL, lang VARCHAR(8) NOT NULL, name VARCHAR(180) NOT NULL, description TEXT NOT NULL,
 PRIMARY KEY(category_id,lang), FOREIGN KEY (category_id) REFERENCES menu_categories(id) ON DELETE CASCADE,
 FOREIGN KEY (lang) REFERENCES supported_languages(code) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS menu_items (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, slug VARCHAR(150) UNIQUE NOT NULL,
 category_id INT UNSIGNED NOT NULL, media_id BIGINT UNSIGNED NULL, price DECIMAL(12,2) NULL DEFAULT NULL,
 show_price TINYINT(1) NOT NULL DEFAULT 0, featured TINYINT(1) NOT NULL DEFAULT 0,
 is_available TINYINT(1) NOT NULL DEFAULT 1, active TINYINT(1) NOT NULL DEFAULT 1,
 sort_order INT NOT NULL DEFAULT 0, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (category_id) REFERENCES menu_categories(id) ON DELETE RESTRICT,
 FOREIGN KEY (media_id) REFERENCES media_library(id) ON DELETE SET NULL,
 INDEX (category_id,active,sort_order), INDEX (featured,active)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS menu_item_translations (
 item_id BIGINT UNSIGNED NOT NULL, lang VARCHAR(8) NOT NULL,
 name VARCHAR(200) NOT NULL, description TEXT NOT NULL,
 PRIMARY KEY(item_id,lang), FOREIGN KEY (item_id) REFERENCES menu_items(id) ON DELETE CASCADE,
 FOREIGN KEY (lang) REFERENCES supported_languages(code) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS gallery_items (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, media_id BIGINT UNSIGNED NOT NULL,
 sort_order INT NOT NULL DEFAULT 0, active TINYINT(1) NOT NULL DEFAULT 1,
 FOREIGN KEY (media_id) REFERENCES media_library(id) ON DELETE CASCADE,
 INDEX(active,sort_order)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS ui_translations (
 lang VARCHAR(8) NOT NULL, translation_key VARCHAR(120) NOT NULL, translated_value TEXT NOT NULL,
 PRIMARY KEY(lang,translation_key), FOREIGN KEY(lang) REFERENCES supported_languages(code) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS admin_activity_logs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, admin_id BIGINT UNSIGNED NULL,
 action VARCHAR(80) NOT NULL, subject VARCHAR(130) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (admin_id) REFERENCES admins(id) ON DELETE SET NULL, INDEX(created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
SET FOREIGN_KEY_CHECKS = 1;
